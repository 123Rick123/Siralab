function float_exponent(number) {
    var exponent = 1;
    while (number < 1.0) {
        exponent += 1;
        number *= 10;
    }
    return exponent;
}
function format_float(number, extraPrecision) {
    var precision = float_exponent(number) + (extraPrecision || 0);
    return number.toFixed(precision).split(/\.?0+$/)[0];
}


